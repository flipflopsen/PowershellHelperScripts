#region Utility functions

function ConvertTo-NormalizedRelativePath {
    param(
        [Parameter(Mandatory)]
        [string]$Path
    )

    $normalized = $Path.Replace("/", "\")
    $normalized = $normalized.TrimStart([char[]]@("\", "/"))

    if ([string]::IsNullOrWhiteSpace($normalized)) {
        return ""
    }

    $segments = $normalized.Split(
        [char[]]@("\", "/"),
        [System.StringSplitOptions]::RemoveEmptyEntries
    )

    if ($segments -contains "..") {
        throw "Unsafe relative path containing '..': '$Path'"
    }

    if ([System.IO.Path]::IsPathRooted($normalized)) {
        throw "Index contains a rooted path: '$Path'"
    }

    return [string]::Join("\", $segments)
}

function Get-RelativeParent {
    param(
        [Parameter(Mandatory)]
        [AllowEmptyString()]
        [string]$RelativePath
    )

    $position = $RelativePath.LastIndexOf("\")

    if ($position -lt 0) {
        return ""
    }

    return $RelativePath.Substring(0, $position)
}

function Get-RelativeLeaf {
    param(
        [Parameter(Mandatory)]
        [string]$RelativePath
    )

    $position = $RelativePath.LastIndexOf("\")

    if ($position -lt 0) {
        return $RelativePath
    }

    return $RelativePath.Substring($position + 1)
}

function Import-PathExclusions {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [string]$Path
    )

    if (-not (Test-Path -LiteralPath $Path -PathType Leaf)) {
        throw "Exclusion file does not exist: '$Path'"
    }

    $filenameParts = [System.Collections.Generic.HashSet[string]]::new(
        [System.StringComparer]::OrdinalIgnoreCase
    )

    $folderParts = [System.Collections.Generic.HashSet[string]]::new(
        [System.StringComparer]::OrdinalIgnoreCase
    )

    $currentSection = $null
    $lineNumber = 0

    foreach ($line in [System.IO.File]::ReadLines($Path)) {
        $lineNumber++
        $trimmedLine = $line.Trim()

        if (
            [string]::IsNullOrWhiteSpace($trimmedLine) -or
            $trimmedLine.StartsWith("#")
        ) {
            continue
        }

        # Accept both:
        #   - FilenameParts:
        # and:
        #   FilenameParts:
        if (
            $trimmedLine -match
            '^(?:-\s*)?(FilenameParts|FolderParts)\s*:\s*$'
        ) {
            $currentSection = $Matches[1]
            continue
        }

        if ($trimmedLine -notmatch '^-\s*(.+?)\s*$') {
            throw (
                "Invalid exclusions file syntax at line {0}: {1}" -f
                $lineNumber,
                $line
            )
        }

        if ($null -eq $currentSection) {
            throw (
                "Exclusion item declared before a section at line {0}: {1}" -f
                $lineNumber,
                $line
            )
        }

        $value = $Matches[1].Trim()

        # Permit simple single- or double-quoted values.
        if (
            $value.Length -ge 2 -and
            (
                (
                    $value.StartsWith('"') -and
                    $value.EndsWith('"')
                ) -or
                (
                    $value.StartsWith("'") -and
                    $value.EndsWith("'")
                )
            )
        ) {
            $value = $value.Substring(1, $value.Length - 2).Trim()
        }

        if ([string]::IsNullOrWhiteSpace($value)) {
            throw "Empty exclusion at line $lineNumber in '$Path'."
        }

        if ($value.IndexOfAny([char[]]@("\", "/")) -ge 0) {
            throw (
                "Exclusion values must be filename or folder-name parts, " +
                "not paths. Invalid value at line ${lineNumber}: '$value'"
            )
        }

        switch ($currentSection) {
            "FilenameParts" {
                [void]$filenameParts.Add($value)
            }

            "FolderParts" {
                [void]$folderParts.Add($value)
            }

            default {
                throw "Unsupported exclusion section '$currentSection'."
            }
        }
    }

    return [PSCustomObject]@{
        FilenameParts = [string[]]@(
            $filenameParts |
                Sort-Object
        )
        FolderParts = [string[]]@(
            $folderParts |
                Sort-Object
        )
    }
}

function Test-UserExcludedPath {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [string]$RelativePath,

        [Parameter(Mandatory)]
        [ValidateSet("F", "D")]
        [string]$RecordType,

        [string[]]$FilenameParts = @(),

        [string[]]$FolderParts = @()
    )

    # Filename exclusions apply only to file records and only to the leaf
    # filename, not to the complete path.
    if ($RecordType -eq "F" -and $FilenameParts.Count -gt 0) {
        $fileName = Get-RelativeLeaf -RelativePath $RelativePath

        foreach ($part in $FilenameParts) {
            if (
                $fileName.IndexOf(
                    $part,
                    [System.StringComparison]::OrdinalIgnoreCase
                ) -ge 0
            ) {
                return $true
            }
        }
    }

    if ($FolderParts.Count -eq 0) {
        return $false
    }

    # For files, inspect only the containing directory components.
    # For directories, inspect the directory itself and all its ancestors.
    $folderPath = if ($RecordType -eq "F") {
        Get-RelativeParent -RelativePath $RelativePath
    }
    else {
        $RelativePath
    }

    if ([string]::IsNullOrWhiteSpace($folderPath)) {
        return $false
    }

    foreach ($folderName in $folderPath.Split("\")) {
        foreach ($part in $FolderParts) {
            if (
                $folderName.IndexOf(
                    $part,
                    [System.StringComparison]::OrdinalIgnoreCase
                ) -ge 0
            ) {
                return $true
            }
        }
    }

    return $false
}

function Test-ExcludedPath {
    param(
        [Parameter(Mandatory)]
        [string]$RelativePath
    )

    foreach ($segment in $RelativePath.Split("\")) {
        if ($ExcludedDirectoryNames.Contains($segment)) {
            return $true
        }
    }

    return $false
}

function Get-MarkerWeight {
    param(
        [Parameter(Mandatory)]
        [string]$FileName
    )

    if ($MarkerWeights.ContainsKey($FileName)) {
        return [int]$MarkerWeights[$FileName]
    }

    $extension = [System.IO.Path]::GetExtension($FileName)

    switch -Regex ($extension) {
        '^\.(sln|slnx)$' {
            return 9
        }

        '^\.(csproj|fsproj|vbproj|vcxproj|sqlproj|wixproj|proj)$' {
            return 8
        }

        '^\.(xcodeproj|xcworkspace)$' {
            return 8
        }

        '^\.(cabal)$' {
            return 6
        }

        default {
            return 0
        }
    }
}

function Get-RelevantFileKind {
    param(
        [Parameter(Mandatory)]
        [string]$RelativePath
    )

    $fileName = Get-RelativeLeaf -RelativePath $RelativePath

    if ($SensitiveFileNames.Contains($fileName)) {
        return $null
    }

    if ($fileName -match '(?i)\.(pem|key|pfx|p12|jks|keystore)$') {
        return $null
    }

    $extension = [System.IO.Path]::GetExtension($fileName)

    if ($SourceExtensions.Contains($extension)) {
        return "Source"
    }

    if ((Get-MarkerWeight -FileName $fileName) -gt 0) {
        return "ProjectMarker"
    }

    if ($RelevantFileNames.Contains($fileName)) {
        return "ProjectMetadata"
    }

    if ($fileName -match '^(?i)(README|CHANGELOG|CHANGES|CONTRIBUTING|AUTHORS|NOTICE|COPYING|LICENSE)(\..+)?$') {
        return "Documentation"
    }

    if ($RelativePath -match '(?i)(^|\\)\.github\\workflows\\.+\.ya?ml$') {
        return "ContinuousIntegration"
    }

    if ($RelativePath -match '(?i)(^|\\)\.devcontainer\\.+$') {
        return "DevelopmentConfiguration"
    }

    return $null
}

function Add-ProjectEvidence {
    param(
        [Parameter(Mandatory)]
        [System.Collections.Generic.Dictionary[string, object]]$Candidates,

        [Parameter(Mandatory)]
        [AllowEmptyString()]
        [string]$ProjectRoot,

        [Parameter(Mandatory)]
        [string]$Evidence,

        [Parameter(Mandatory)]
        [int]$Weight
    )

    # A project marker in the root of the indexed source does not establish a
    # safe extraction boundary. Such files remain unclassified.
    if ([string]::IsNullOrWhiteSpace($ProjectRoot)) {
        return
    }

    if (-not $Candidates.ContainsKey($ProjectRoot)) {
        $Candidates[$ProjectRoot] = [PSCustomObject]@{
            Root = $ProjectRoot
            Score = 0
            Evidence = [System.Collections.Generic.HashSet[string]]::new(
                [System.StringComparer]::OrdinalIgnoreCase
            )
        }
    }

    $candidate = $Candidates[$ProjectRoot]

    if ($candidate.Evidence.Add($Evidence)) {
        $candidate.Score += $Weight
    }
}

function Get-StableShortHash {
    param(
        [Parameter(Mandatory)]
        [string]$Text
    )

    $bytes = [System.Text.Encoding]::UTF8.GetBytes($Text)
    $hash = [System.Security.Cryptography.SHA256]::HashData($bytes)

    return [System.Convert]::ToHexString($hash).Substring(0, 10).ToLowerInvariant()
}

function ConvertTo-SafeDirectoryName {
    param(
        [Parameter(Mandatory)]
        [string]$Name
    )

    $invalidCharacters = [System.IO.Path]::GetInvalidFileNameChars()

    foreach ($character in $invalidCharacters) {
        $Name = $Name.Replace($character, "_")
    }

    $Name = $Name.Trim().TrimEnd(".")

    if ([string]::IsNullOrWhiteSpace($Name)) {
        return "UnnamedProject"
    }

    if ($Name.Length -gt 80) {
        return $Name.Substring(0, 80)
    }

    return $Name
}

function Find-ContainingProjectRoot {
    param(
        [Parameter(Mandatory)]
        [string]$FileRelativePath,

        [Parameter(Mandatory)]
        [System.Collections.Generic.Dictionary[string, object]]$ProjectByRoot
    )

    $directory = Get-RelativeParent -RelativePath $FileRelativePath

    while (-not [string]::IsNullOrEmpty($directory)) {
        if ($ProjectByRoot.ContainsKey($directory)) {
            return $directory
        }

        $parent = Get-RelativeParent -RelativePath $directory

        if ($parent -eq $directory) {
            break
        }

        $directory = $parent
    }

    return $null
}

function ConvertTo-CsvField {
    param(
        [AllowNull()]
        [object]$Value
    )

    if ($null -eq $Value) {
        return '""'
    }

    $text = [string]$Value
    return '"' + $text.Replace('"', '""') + '"'
}

