#requires -Version 7.2

<#
.SYNOPSIS
    Detects programming projects and extracts relevant source files using a
    DriveArchive index.

.DESCRIPTION
    The script consumes index records in the following format:

        F<TAB>relative\file\path.ext
        D<TAB>relative\directory

    Projects are detected through repository and build-system markers such as:

        .git
        *.sln
        *.csproj
        package.json
        pyproject.toml
        Cargo.toml
        go.mod
        pom.xml
        CMakeLists.txt
        Makefile
        Dockerfile

    In Analyze mode, only reports are created.

    In Extract mode, relevant files are copied from SourceRoot into an isolated
    extraction directory. The source filesystem is never modified.

    Files not associated with a detected project are retained under
    "_Unclassified", preserving their original relative paths.

.NOTES
    Project detection is heuristic. No finite marker list can identify every
    historical or proprietary project layout.

    Review the generated manifests before publishing extracted files. Source
    trees may contain credentials, private keys, tokens, personal data,
    proprietary code, or confidential configuration.
#>

[CmdletBinding(SupportsShouldProcess)]
param(
    # Index generated by DriveArchive.ps1.
    [Parameter(Mandatory)]
    [ValidateScript({ Test-Path -LiteralPath $_ -PathType Leaf })]
    [string]$IndexPath,

    # Original source corresponding to the index.
    # Required for Extract mode and used to validate source paths.
    [Parameter(Mandatory)]
    [ValidateScript({ Test-Path -LiteralPath $_ -PathType Container })]
    [string]$SourceRoot,

    # Parent directory in which the analysis/extraction run is created.
    [Parameter(Mandatory)]
    [string]$OutputRoot,

    [ValidateSet("Analyze", "Extract")]
    [string]$Mode = "Analyze",

    # Minimum accumulated marker score required for a detected project.
    [ValidateRange(1, 100)]
    [int]$MinimumProjectScore = 3,

    # Disable Write-Progress output.
    [switch]$NoProgress,

    # Replace an existing run directory with the same RunName.
    [switch]$Force,

    # Optional deterministic run-directory name.
    [ValidatePattern('^[^<>:"/\\|?*]+$')]
    [string]$RunName,

    # YAML-like exclusion file. The default location is exclusions.txt beside
    # this script.
    [string]$ExclusionsPath = (Join-Path $PSScriptRoot "exclusions.txt")
)

Set-StrictMode -Version Latest
