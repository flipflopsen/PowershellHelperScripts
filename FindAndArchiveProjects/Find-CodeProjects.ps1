#region Read index and identify evidence

$projectCandidates =
    [System.Collections.Generic.Dictionary[string, object]]::new(
        [System.StringComparer]::OrdinalIgnoreCase
    )

$relevantFiles = [System.Collections.Generic.List[string]]::new()

$indexedFileCount = 0L
$indexedDirectoryCount = 0L
$excludedRecordCount = 0L
$userExcludedRecordCount = 0L
$relevantRecordCount = 0L
$invalidRecordCount = 0L

$reader = [System.IO.StreamReader]::new(
    $resolvedIndexPath,
    [System.Text.Encoding]::UTF8,
    $true,
    1MB
)

try {
    while (-not $reader.EndOfStream) {
        $line = $reader.ReadLine()

        if ([string]::IsNullOrWhiteSpace($line)) {
            continue
        }

        $separatorPosition = $line.IndexOf("`t")

        if ($separatorPosition -lt 1) {
            # DriveArchive headers and unrelated metadata are ignored.
            continue
        }

        $recordType = $line.Substring(0, $separatorPosition)
        $rawRelativePath = $line.Substring($separatorPosition + 1)

        if ($recordType -notin @("F", "D")) {
            continue
        }

        try {
            $relativePath = ConvertTo-NormalizedRelativePath `
                -Path $rawRelativePath
        }
        catch {
            $invalidRecordCount++
            Write-Warning $_.Exception.Message
            continue
        }

        if ([string]::IsNullOrWhiteSpace($relativePath)) {
            continue
        }

        # Apply user exclusions before directory-marker detection, project evidence
        # collection, source classification, or report generation.
        if (
            Test-UserExcludedPath `
                -RelativePath $relativePath `
                -RecordType $recordType `
                -FilenameParts $pathExclusions.FilenameParts `
                -FolderParts $pathExclusions.FolderParts
        ) {
            $userExcludedRecordCount++
            continue
        }

        if ($recordType -eq "D") {
            $indexedDirectoryCount++

            # Directory-based project markers must be processed before the
            # directory itself is excluded from file extraction.
            $directoryName = Get-RelativeLeaf -RelativePath $relativePath
            $directoryParent = Get-RelativeParent -RelativePath $relativePath

            if (
                $directoryName.Equals(
                    ".git",
                    [System.StringComparison]::OrdinalIgnoreCase
                )
            ) {
                Add-ProjectEvidence `
                    -Candidates $projectCandidates `
                    -ProjectRoot $directoryParent `
                    -Evidence ".git directory" `
                    -Weight 10
            }
            elseif (
                $directoryName -match
                '(?i)\.(xcodeproj|xcworkspace)$'
            ) {
                Add-ProjectEvidence `
                    -Candidates $projectCandidates `
                    -ProjectRoot $directoryParent `
                    -Evidence $directoryName `
                    -Weight 8
            }

            continue
        }

        $indexedFileCount++

        if (Test-ExcludedPath -RelativePath $relativePath) {
            $excludedRecordCount++
            continue
        }

        $fileName = Get-RelativeLeaf -RelativePath $relativePath
        $markerWeight = Get-MarkerWeight -FileName $fileName

        if ($markerWeight -gt 0) {
            $candidateRoot = Get-RelativeParent `
                -RelativePath $relativePath

            Add-ProjectEvidence `
                -Candidates $projectCandidates `
                -ProjectRoot $candidateRoot `
                -Evidence $fileName `
                -Weight $markerWeight
        }

        $kind = Get-RelevantFileKind -RelativePath $relativePath

        if ($null -ne $kind) {
            $relevantFiles.Add($relativePath)
            $relevantRecordCount++
        }

        if (
            -not $NoProgress -and
            ($indexedFileCount % 50000L) -eq 0
        ) {
            $statusFormat = (
            "{0:N0} files read | {1:N0} relevant | " +
            "{2:N0} excluded by rules | {3:N0} candidate roots"
        )

        $status = $statusFormat -f @(
            $indexedFileCount,
            $relevantRecordCount,
            $userExcludedRecordCount,
            $projectCandidates.Count
        )

            Write-Progress `
                -Id 20 `
                -Activity "Analyzing DriveArchive index" `
                -Status $status `
                -CurrentOperation $relativePath
        }
    }
}
finally {
    $reader.Dispose()

    if (-not $NoProgress) {
        Write-Progress `
            -Id 20 `
            -Activity "Analyzing DriveArchive index" `
            -Completed
    }
}

#endregion Read index and identify evidence

#region Select projects

$projectByRoot =
    [System.Collections.Generic.Dictionary[string, object]]::new(
        [System.StringComparer]::OrdinalIgnoreCase
    )

$projects = [System.Collections.Generic.List[object]]::new()

foreach ($candidate in $projectCandidates.Values) {
    if ($candidate.Score -lt $MinimumProjectScore) {
        continue
    }

    $leafName = Get-RelativeLeaf -RelativePath $candidate.Root
    $safeName = ConvertTo-SafeDirectoryName -Name $leafName
    $shortHash = Get-StableShortHash -Text $candidate.Root
    $destinationName = "{0}--{1}" -f $safeName, $shortHash

    $project = [PSCustomObject]@{
        Id = $shortHash
        Name = $leafName
        RelativeRoot = $candidate.Root
        Score = [int]$candidate.Score
        Evidence = @($candidate.Evidence | Sort-Object)
        DestinationName = $destinationName
        RelevantFileCount = 0L
        SourceFileCount = 0L
        MissingFileCount = 0L
        CopyErrorCount = 0L
    }

    $projectByRoot[$candidate.Root] = $project
    $projects.Add($project)
}

#endregion Select projects

#region Classify files

$unclassifiedRelevantCount = 0L
$unclassifiedSourceCount = 0L

foreach ($relativePath in $relevantFiles) {
    $projectRoot = Find-ContainingProjectRoot `
        -FileRelativePath $relativePath `
        -ProjectByRoot $projectByRoot

    $kind = Get-RelevantFileKind -RelativePath $relativePath

    if ($null -ne $projectRoot) {
        $project = $projectByRoot[$projectRoot]
        $project.RelevantFileCount++

        if ($kind -eq "Source") {
            $project.SourceFileCount++
        }
    }
    else {
        $unclassifiedRelevantCount++

        if ($kind -eq "Source") {
            $unclassifiedSourceCount++
        }
    }
}

#endregion Classify files

#region Write project report

$projectsCsvPath = Join-Path $reportDirectory "projects.csv"

$projects |
    Sort-Object RelativeRoot |
    Select-Object @(
        "Id"
        "Name"
        "RelativeRoot"
        "Score"
        "RelevantFileCount"
        "SourceFileCount"
        @{
            Name = "Evidence"
            Expression = { $_.Evidence -join "; " }
        }
        "DestinationName"
    ) |
    Export-Csv `
        -LiteralPath $projectsCsvPath `
        -NoTypeInformation `
        -Encoding utf8

#endregion Write project report

#region Extract or manifest files

$filesCsvPath = Join-Path $reportDirectory "files.csv"

$filesWriter = [System.IO.StreamWriter]::new(
    $filesCsvPath,
    $false,
    [System.Text.UTF8Encoding]::new($true),
    1MB
)

$createdDirectories = [System.Collections.Generic.HashSet[string]]::new(
    [System.StringComparer]::OrdinalIgnoreCase
)

$processedRelevantFiles = 0L
$copiedFileCount = 0L
$missingFileCount = 0L
$copyErrorCount = 0L

try {
    $filesWriter.WriteLine(
        '"SourceRelativePath","Kind","ProjectId","ProjectRoot",' +
        '"DestinationRelativePath","Status","Error"'
    )

    foreach ($relativePath in $relevantFiles) {
        $processedRelevantFiles++

        $kind = Get-RelevantFileKind -RelativePath $relativePath

        if ($null -eq $kind) {
            continue
        }

        $projectRoot = Find-ContainingProjectRoot `
            -FileRelativePath $relativePath `
            -ProjectByRoot $projectByRoot

        $projectId = ""
        $destinationRelativePath = ""
        $project = $null

        if ($null -ne $projectRoot) {
            $project = $projectByRoot[$projectRoot]
            $projectId = $project.Id

            $prefixLength = $projectRoot.Length

            if ($relativePath.Length -gt $prefixLength) {
                $insideProject = $relativePath.Substring(
                    $prefixLength
                ).TrimStart("\")
            }
            else {
                $insideProject = Get-RelativeLeaf `
                    -RelativePath $relativePath
            }

            $destinationRelativePath = Join-Path `
                $project.DestinationName `
                $insideProject
        }
        else {
            $destinationRelativePath = Join-Path `
                "_Unclassified" `
                $relativePath
        }

        $sourcePath = Join-Path $resolvedSourceRoot $relativePath
        $destinationPath = Join-Path `
            $extractionDirectory `
            $destinationRelativePath

        $status = "Analyzed"
        $errorText = ""

        if ($Mode -eq "Extract") {
            if (-not [System.IO.File]::Exists($sourcePath)) {
                $status = "Missing"
                $missingFileCount++

                if ($null -ne $project) {
                    $project.MissingFileCount++
                }
            }
            elseif (
                $PSCmdlet.ShouldProcess(
                    $sourcePath,
                    "Copy to '$destinationPath'"
                )
            ) {
                try {
                    $destinationParent = [System.IO.Path]::GetDirectoryName(
                        $destinationPath
                    )

                    if ($createdDirectories.Add($destinationParent)) {
                        [void][System.IO.Directory]::CreateDirectory(
                            $destinationParent
                        )
                    }

                    [System.IO.File]::Copy(
                        $sourcePath,
                        $destinationPath,
                        $true
                    )

                    # Preserve basic timestamps without copying ACLs,
                    # alternate data streams, or filesystem ownership.
                    $sourceInfo = [System.IO.FileInfo]::new($sourcePath)
                    $destinationInfo = [System.IO.FileInfo]::new(
                        $destinationPath
                    )

                    $destinationInfo.CreationTimeUtc =
                        $sourceInfo.CreationTimeUtc

                    $destinationInfo.LastWriteTimeUtc =
                        $sourceInfo.LastWriteTimeUtc

                    $status = "Copied"
                    $copiedFileCount++
                }
                catch {
                    $status = "CopyError"
                    $errorText = $_.Exception.Message
                    $copyErrorCount++

                    if ($null -ne $project) {
                        $project.CopyErrorCount++
                    }
                }
            }
            else {
                $status = "WhatIf"
            }
        }

        $csvFields = @(
            ConvertTo-CsvField $relativePath
            ConvertTo-CsvField $kind
            ConvertTo-CsvField $projectId
            ConvertTo-CsvField $projectRoot
            ConvertTo-CsvField $destinationRelativePath
            ConvertTo-CsvField $status
            ConvertTo-CsvField $errorText
        )

        $filesWriter.WriteLine([string]::Join(",", $csvFields))

        if (
            -not $NoProgress -and
            (
                ($processedRelevantFiles % 1000L) -eq 0 -or
                $processedRelevantFiles -eq $relevantFiles.Count
            )
        ) {
            $percentComplete = if ($relevantFiles.Count -gt 0) {
                [Math]::Min(
                    100,
                    [int](
                        100.0 *
                        $processedRelevantFiles /
                        $relevantFiles.Count
                    )
                )
            }
            else {
                100
            }

            $statusText = if ($Mode -eq "Extract") {
                "{0:N0}/{1:N0} files | {2:N0} copied | " +
                "{3:N0} missing | {4:N0} errors" -f @(
                    $processedRelevantFiles,
                    $relevantFiles.Count,
                    $copiedFileCount,
                    $missingFileCount,
                    $copyErrorCount
                )
            }
            else {
                "{0:N0}/{1:N0} relevant files classified" -f @(
                    $processedRelevantFiles,
                    $relevantFiles.Count
                )
            }

            Write-Progress `
                -Id 21 `
                -Activity "$Mode relevant project files" `
                -Status $statusText `
                -PercentComplete $percentComplete `
                -CurrentOperation $relativePath
        }
    }
}
finally {
    $filesWriter.Dispose()

    if (-not $NoProgress) {
        Write-Progress `
            -Id 21 `
            -Activity "$Mode relevant project files" `
            -Completed
    }
}

#endregion Extract or manifest files

